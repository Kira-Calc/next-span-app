/// Minimal SVG path reader for the absolute M, L, H, V, C, Z commands these exports use.
struct SVGPathShape: Shape {
    let d: String
    let viewBox: CGFloat = 113.38

    func path(in rect: CGRect) -> Path {
        let k = min(rect.width, rect.height) / viewBox
        var p = Path()
        var cur = CGPoint.zero
        var start = CGPoint.zero
        let scanner = Scanner(string: d)
        scanner.charactersToBeSkipped = CharacterSet(charactersIn: " ,\n")
        var cmd: Character = "M"
        func num() -> CGFloat { CGFloat(scanner.scanDouble() ?? 0) }
        func pt(_ x: CGFloat, _ y: CGFloat) -> CGPoint { CGPoint(x: rect.minX + x * k, y: rect.minY + y * k) }
        while !scanner.isAtEnd {
            if let c = scanner.scanCharacter(), c.isLetter {
                cmd = c
            } else {
                scanner.currentIndex = scanner.string.index(before: scanner.currentIndex)
            }
            switch cmd {
            case "M":
                cur = CGPoint(x: num(), y: num()); start = cur
                p.move(to: pt(cur.x, cur.y)); cmd = "L"
            case "L":
                cur = CGPoint(x: num(), y: num()); p.addLine(to: pt(cur.x, cur.y))
            case "H":
                cur.x = num(); p.addLine(to: pt(cur.x, cur.y))
            case "V":
                cur.y = num(); p.addLine(to: pt(cur.x, cur.y))
            case "C":
                let c1 = CGPoint(x: num(), y: num()), c2 = CGPoint(x: num(), y: num()), e = CGPoint(x: num(), y: num())
                p.addCurve(to: pt(e.x, e.y), control1: pt(c1.x, c1.y), control2: pt(c2.x, c2.y)); cur = e
            case "Z":
                p.closeSubpath(); cur = start
                if scanner.isAtEnd { break }
            default:
                _ = scanner.scanCharacter()
            }
        }
        return p
    }
}

